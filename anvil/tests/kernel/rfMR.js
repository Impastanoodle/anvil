  // --- rfMR (2026-11-15, lane MR stepfree) --- free-form faces through Anvil's STEP reader and writer.
  // (1) The reader keeps each B-spline face it reads (freeFace, splineFace, ruledFace) with the Imported feature's solid
  //     (solid.free: the surface, its edges' curves, which triangles are its); the writer (freeFacesOf, writeFreeFace)
  //     finds those faces whole in the body (a hole elsewhere splits their triangles: the pieces still count) and writes
  //     them as B_SPLINE_SURFACE_WITH_KNOTS (the RATIONAL complex entity when it was) bounded by their own edges, which
  //     the planes and cylinders beside them share. Was: planar facets (a loft's four sides: 96 PLANE faces).
  // (2) A whole closed B-spline face (OpenCascade's NURBS sphere: one VERTEX_LOOP) was refused; it is read as the
  //     surface's whole domain (wholePatch).
  // (3) A free-form face's triangles with all three corners on its boundary get a point at their centre, so
  //     freeVolumeFix can move it (centreInsert): the variable blend's volume 3.4e-6 -> 1e-7 of OpenCascade's.
  // Inputs: written by OpenCascade 7.6 (mm), its volumes (VolumePropertiesGK, 1e-10) inline. OpenCascade read every
  // Anvil re-export of them back as one valid closed solid with these volumes to 1e-10 (measured, lane MR report).
