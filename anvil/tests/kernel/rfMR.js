    group('rfMR: STEP free-form faces: imported B-spline faces written back as B-spline faces, a whole NURBS sphere read');
    var X = typeof Exchange !== 'undefined' ? Exchange : null;
    function rfMRread(step) {
      if (!X) fail('exchange.js is not loaded');
      var res = X.importFile('rfMR.step', step, { units: 'mm' }), m = X.newPartFromImport(res), b = K.rebuild(m);
      var mp = K.massProps(K.meshFromBody(b.body), 1);
      return { res: res, model: m, build: b, volume: mp.volume, closed: typeof Evaluate === 'undefined' || Evaluate.checkBody(b.body, { maxPairs: 1 }).ok };
    }
    // the surface kind of every ADVANCED_FACE of a STEP text written by Anvil (one entity a line): { PLANE: n, BSPLINE: n, ... }
    function rfMRfaces(s) {
      var ent = {}, out = {};
      s.split('\n').forEach(function (l) { var m = /^#(\d+)=(.*);$/.exec(l); if (m) ent[m[1]] = m[2]; });
      Object.keys(ent).forEach(function (id) {
        var m = /^ADVANCED_FACE\(.*,#(\d+),\.[TF]\.\)$/.exec(ent[id]);
        if (!m) return;
        var sf = ent[m[1]] || '', k = /B_SPLINE_SURFACE/.test(sf) ? 'BSPLINE' : (/^([A-Z_]+)\(/.exec(sf) || [])[1] || 'complex';
        out[k] = (out[k] || 0) + 1;
      });
      return out;
    }
    // import -> export -> import -> export: the faces written each time, the triangles read each time
    function rfMRtrip(step, occ, volTol) {
      var r0 = rfMRread(step);
      assert(!r0.res.stats.openEdges, 'open edges: ' + r0.res.stats.openEdges);
      assert(r0.closed, 'closed solid');
      nearRel(r0.volume, occ, volTol, 'volume read');
      var s1 = X.exportSTEP(r0.model, r0.build), r1 = rfMRread(s1), s2 = X.exportSTEP(r1.model, r1.build), r2 = rfMRread(s2);
      [r1, r2].forEach(function (r, i) {
        assert(!r.res.stats.openEdges && r.closed, 'generation ' + (i + 1) + ' read closed (open edges ' + r.res.stats.openEdges + ')');
        assert(Math.abs(r.res.stats.triangles - r0.res.stats.triangles) <= 0.02 * r0.res.stats.triangles, 'generation ' + (i + 1) + ': ' + r.res.stats.triangles + ' triangles, the file ' + r0.res.stats.triangles);
        nearRel(r.volume, r0.volume, 1e-9, 'generation ' + (i + 1) + ' volume');
      });
      var f1 = rfMRfaces(s1), f2 = rfMRfaces(s2);
      assert(JSON.stringify(f1) === JSON.stringify(f2), 'second round trip writes the same faces: ' + JSON.stringify(f1) + ' / ' + JSON.stringify(f2));
      return { r0: r0, s1: s1, faces: f1 };
    }
