      s = r.recompute();
      var comp2 = s.prims.filter(function (p) { return p.fmt === 'field:company'; })[0];
      assert(rfAENear(comp2.p[0], x0 - 1) && rfAENear(comp2.p[1], y0 + 0.5), 'label moved 1 in left, .5 in up');
      var c2 = DW.titleFieldAt(s.size, 'in', [x0 - 1 + 0.05, y0 + 0.5], r.doc);
      assert(c2 && c2.field.key === 'company', 'the moved cell is where the text went');
      var nRow = s.prims.filter(function (p) { return p.fmt === 'tb-row1'; }).length;
      DW.deleteFormatItem(r.doc, 'tb-row1');
      DW.deleteFormatItem(r.doc, 'field:dwgNo');
      s = r.recompute();
